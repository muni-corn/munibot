use async_trait::async_trait;
use munibot_config::{Configurable, RefKind};

use crate::provider::context::{ConfigContext, ConfigError};

/// A configuration provider: something (a handler, a subsystem) whose
/// settings can be read and written through the gui.
///
/// Implementors write only `read` and `write`, plus `on_changed`/
/// `ref_options` when they need them; everything else -- the schema,
/// patch merging, validation -- comes from `Self::Config: Configurable`
/// (see `munibot_config`) and the `DynConfigProvider` blanket impl that
/// bridges this trait to a form the `ConfigRegistry` can store as a trait
/// object.
///
/// There is deliberately no `descriptor()` method here: `Self::Config`
/// already has one (`Configurable::descriptor()`, generated by
/// `#[derive(Configurable)]` from `#[config(id = ..., label = ..., scope =
/// ...)]` on the config struct itself), and a second, separately
/// implemented one on the provider would just be a second place that
/// identity could drift from the first. See docs/notes.
#[async_trait]
pub trait ConfigurationProvider: Send + Sync + 'static {
    /// The struct describing this provider's settings.
    type Config: Configurable + Send + Sync;

    /// Loads persisted settings for `ctx.scope`, or `Self::Config::default()`
    /// if none are saved yet.
    async fn read(&self, ctx: &ConfigContext) -> Result<Self::Config, ConfigError>;

    /// Persists `desired`. `previous` is supplied so collection-backed
    /// providers (a `BTreeMap<K, V>` field) can compute a minimal set of
    /// inserts, updates, and deletes -- see `collection_diff`.
    async fn write(
        &self,
        ctx: &ConfigContext,
        previous: &Self::Config,
        desired: &Self::Config,
    ) -> Result<(), ConfigError>;

    /// Runs after a successful `write`. Override to invalidate any
    /// in-memory cache this provider's bot-side handler keeps (e.g.
    /// autodelete's loaded timers), so a gui write takes effect
    /// immediately rather than waiting for the handler to notice on its
    /// own.
    async fn on_changed(
        &self,
        _ctx: &ConfigContext,
        _config: &Self::Config,
    ) -> Result<(), ConfigError> {
        Ok(())
    }

    /// Candidate values for one of this provider's `Ref` fields (e.g. a
    /// channel picker). Returns an empty list by default; override for any
    /// provider with a `Ref`-kinded field in its schema.
    async fn ref_options(
        &self,
        _ctx: &ConfigContext,
        _kind: RefKind,
    ) -> Result<Vec<RefOption>, ConfigError> {
        Ok(Vec::new())
    }
}

/// One candidate value for a `Ref` field, e.g. one discord channel a
/// logging provider's channel picker could show.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RefOption {
    /// The value a `ConfigValue::Ref` should carry if this option is
    /// chosen -- a snowflake as text, matching `ConfigValue::Ref` itself.
    pub id: String,
    pub label: String,
    /// An optional grouping label, e.g. a category name channels are
    /// grouped under.
    pub group: Option<String>,
}

#[cfg(test)]
pub(crate) mod test_support {
    use diesel_async::pooled_connection::{AsyncDieselConnectionManager, bb8::Pool};

    use crate::db::DbPool;

    /// A `DbPool` that never actually connects, for tests of provider code
    /// that never touches `ConfigContext.db`.
    ///
    /// `Pool::build` (used by `establish_pool`) waits for a real
    /// connection and would hang/fail against this bogus address.
    /// `build_unchecked` returns immediately and only spawns a background
    /// connection attempt, which is safe to construct and drop without a
    /// database as long as nothing actually calls `.get()` on it.
    pub(crate) fn unconnected_db_pool() -> DbPool {
        let manager = AsyncDieselConnectionManager::new("mysql://127.0.0.1:1/does_not_exist");
        Pool::builder().build_unchecked(manager)
    }
}

#[cfg(test)]
mod tests {
    use async_trait::async_trait;
    use munibot_config::{
        ConfigNode, ConfigScope, Configurable, ProviderDescriptor, RefKind, ScopeKind,
    };
    use serde::{Deserialize, Serialize};

    use super::ConfigurationProvider;
    use crate::provider::{
        context::{ConfigContext, ConfigError},
        typed::test_support::unconnected_db_pool,
    };

    #[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
    struct NoopConfig;

    impl Configurable for NoopConfig {
        fn config_fields() -> Vec<ConfigNode> {
            Vec::new()
        }

        fn descriptor() -> ProviderDescriptor {
            ProviderDescriptor {
                id: "noop".to_owned(),
                label: "noop".to_owned(),
                description: None,
                icon: None,
                scopes: vec![ScopeKind::DiscordGuild],
            }
        }
    }

    struct NoopProvider;

    #[async_trait]
    impl ConfigurationProvider for NoopProvider {
        type Config = NoopConfig;

        async fn read(&self, _ctx: &ConfigContext) -> Result<Self::Config, ConfigError> {
            Ok(NoopConfig)
        }

        async fn write(
            &self,
            _ctx: &ConfigContext,
            _previous: &Self::Config,
            _desired: &Self::Config,
        ) -> Result<(), ConfigError> {
            Ok(())
        }
    }

    fn test_context() -> ConfigContext {
        ConfigContext {
            db: unconnected_db_pool(),
            scope: ConfigScope::DiscordGuild {
                guild_id: "1".to_owned(),
            },
            actor: None,
        }
    }

    #[tokio::test]
    async fn test_default_on_changed_is_ok() {
        let result = NoopProvider.on_changed(&test_context(), &NoopConfig).await;
        assert!(result.is_ok());
    }

    #[tokio::test]
    async fn test_default_ref_options_is_an_empty_list() {
        let options = NoopProvider
            .ref_options(&test_context(), RefKind::DiscordChannel)
            .await
            .expect("should not error");
        assert!(options.is_empty());
    }
}
