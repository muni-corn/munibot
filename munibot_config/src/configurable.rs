use serde::{Serialize, de::DeserializeOwned};

use crate::{
    descriptor::ProviderDescriptor,
    flatten::{flatten, unflatten},
    node::{ConfigNode, ConfigSchema},
    patch::{ConfigPatch, FieldError},
    path::ConfigPath,
    value::{ConfigValue, ConfigValues},
};

/// A struct describing a set of related settings, whose shape is also its
/// gui schema.
///
/// `#[derive(Configurable)]` (`munibot_config_derive`, phase 2) generates
/// `config_fields` (always) and `descriptor` (only when the container has
/// `#[config(id = ..., label = ..., scope = ...)]` attributes). This is a
/// deliberate split from docs/plans/gui-configuration.md section 5.5, which
/// described a single derived `config_schema()`: that doesn't compose,
/// because nested structs (e.g. the settings inside a `Toggled<T>`, or a
/// `Collection`'s item type) need `config_fields` to build their parent's
/// tree but have no provider identity of their own to put in a
/// `ProviderDescriptor`. See docs/notes/config-schema-implementation-notes.md.
///
/// `to_values` and `with_patch` are provided methods, written once here
/// rather than generated per type: they only need `config_fields`, and go
/// through `serde_json` plus this crate's `flatten`/`unflatten` rather than
/// any type-specific code.
pub trait Configurable: Serialize + DeserializeOwned + Default + Sized {
    /// This struct's own fields, translated into schema nodes.
    fn config_fields() -> Vec<ConfigNode>;

    /// This type's provider identity.
    ///
    /// Only meaningful -- and only generated by the derive -- for a
    /// provider's root `Self::Config` type. Panics if called on a type used
    /// only as nested `Section` or `Collection` item content, which is a
    /// programmer error (such a type was never meant to be registered with
    /// a `ConfigurationProvider`).
    fn descriptor() -> ProviderDescriptor {
        panic!(
            "`{}` has no #[config(id = ...)] and is not a configuration provider's root type",
            std::any::type_name::<Self>()
        )
    }

    /// Cross-field validation beyond what the schema's static constraints
    /// (min/max/required/...) already check. Most types need no override.
    fn validate(&self) -> Result<(), Vec<FieldError>> {
        Ok(())
    }

    /// This provider's full schema: its identity plus its tree of fields.
    fn config_schema() -> ConfigSchema {
        ConfigSchema {
            descriptor: Self::descriptor(),
            root: Self::config_fields(),
        }
    }

    /// Flattens this value into a `ConfigValues` map.
    fn to_values(&self) -> ConfigValues {
        let json = serde_json::to_value(self)
            .expect("a Configurable struct must serialize to a json object");
        flatten(&Self::config_fields(), &json)
    }

    /// Applies `patch` on top of `self`, producing a new, validated value.
    ///
    /// Setting a path to `ConfigValue::Unset` removes it, and everything
    /// nested under it, from the merged values -- not just that one path.
    /// For a scalar field this is how an `Option<T>` gets cleared back to
    /// `None` (falling through to the field's default, same as it never
    /// having been set). For a `Collection` item's own path (e.g.
    /// `timers[9001]`, with no field suffix), this is also the only way to
    /// remove that entire item: every path nested under it disappears, so
    /// `unflatten`'s `collection_keys` scan no longer finds that key at all.
    /// There's no separate "remove" value or a distinct delete operation on
    /// `ConfigPatch` -- an add is just a change to a path that didn't
    /// already exist (its fields fall back to their schema defaults), so
    /// this is add's natural inverse.
    ///
    /// Every changed path is then coerced against its field's real type
    /// (via `unflatten`) before anything is deserialized, so a bad patch is
    /// reported as `FieldError`s by path rather than a raw, path-less
    /// deserialize failure. `serde_path_to_error` is used as defense in
    /// depth for whatever this crate's own coercion doesn't catch.
    fn with_patch(&self, patch: &ConfigPatch) -> Result<Self, Vec<FieldError>> {
        let fields = Self::config_fields();

        let mut values = self.to_values();
        for change in &patch.changes {
            if change.value == ConfigValue::Unset {
                let removed_prefix = change.path.segments();
                values.retain(|path, _| !path.segments().starts_with(removed_prefix));
            } else {
                values.insert(change.path.clone(), change.value.clone());
            }
        }

        let json = unflatten(&fields, &values)?;

        let deserialized: Self = serde_path_to_error::deserialize(json).map_err(|error| {
            let path = error
                .path()
                .to_string()
                .parse::<ConfigPath>()
                .unwrap_or_else(|_| ConfigPath::root());
            vec![FieldError::new(path, error.to_string())]
        })?;

        deserialized.validate()?;
        Ok(deserialized)
    }
}

#[cfg(test)]
mod tests {
    use serde::{Deserialize, Serialize};

    use super::Configurable;
    use crate::{
        descriptor::ProviderDescriptor,
        field::{Field, FieldKind, RefKind},
        node::ConfigNode,
        patch::{ConfigPatch, FieldError},
        path::ConfigPath,
        scope::ScopeKind,
        value::ConfigValue,
    };

    #[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
    struct LoggingSettings {
        channel: Option<u64>,
    }

    // stands in for what `#[derive(Configurable)]` will generate in phase 2.
    impl Configurable for LoggingSettings {
        fn config_fields() -> Vec<ConfigNode> {
            vec![ConfigNode::Field(Field::new(
                "channel",
                "log channel",
                FieldKind::Ref {
                    kind: RefKind::DiscordChannel,
                },
            ))]
        }

        fn descriptor() -> ProviderDescriptor {
            ProviderDescriptor {
                id: "logging".to_owned(),
                label: "server logging".to_owned(),
                description: None,
                icon: None,
                scopes: vec![ScopeKind::DiscordGuild],
            }
        }
    }

    #[test]
    fn test_config_schema_combines_descriptor_and_fields() {
        let schema = LoggingSettings::config_schema();
        assert_eq!(schema.descriptor.id, "logging");
        assert_eq!(schema.root.len(), 1);
    }

    #[test]
    #[should_panic(expected = "is not a configuration provider's root type")]
    fn test_descriptor_panics_for_a_type_without_one() {
        #[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
        struct Nested;

        impl Configurable for Nested {
            fn config_fields() -> Vec<ConfigNode> {
                vec![]
            }
        }

        Nested::descriptor();
    }

    #[test]
    fn test_to_values_reflects_current_state() {
        let settings = LoggingSettings {
            channel: Some(6437),
        };
        let values = settings.to_values();
        assert_eq!(
            values.get(&ConfigPath::root().field("channel")),
            Some(&ConfigValue::Ref("6437".to_owned()))
        );
    }

    #[test]
    fn test_with_patch_applies_a_change() {
        let settings = LoggingSettings { channel: None };
        let patch = ConfigPatch::new().with(
            ConfigPath::root().field("channel"),
            ConfigValue::Ref("6437".to_owned()),
        );

        let updated = settings.with_patch(&patch).expect("patch should apply");
        assert_eq!(updated.channel, Some(6437));
    }

    #[test]
    fn test_with_patch_unset_clears_an_optional_field_back_to_default() {
        let settings = LoggingSettings {
            channel: Some(6437),
        };
        let patch =
            ConfigPatch::new().with(ConfigPath::root().field("channel"), ConfigValue::Unset);

        let updated = settings.with_patch(&patch).expect("patch should apply");
        assert_eq!(updated.channel, None);
    }

    #[test]
    fn test_with_patch_leaves_untouched_fields_alone() {
        let settings = LoggingSettings {
            channel: Some(6437),
        };
        let updated = settings
            .with_patch(&ConfigPatch::new())
            .expect("empty patch should apply");
        assert_eq!(updated, settings);
    }

    #[test]
    fn test_with_patch_rejects_an_unparsable_reference() {
        let settings = LoggingSettings { channel: None };
        let patch = ConfigPatch::new().with(
            ConfigPath::root().field("channel"),
            ConfigValue::Ref("not a number".to_owned()),
        );

        let errors = settings.with_patch(&patch).unwrap_err();
        assert_eq!(errors.len(), 1);
        assert_eq!(errors[0].path, ConfigPath::root().field("channel"));
    }

    #[test]
    fn test_with_patch_runs_validate() {
        #[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
        struct MustBePositive {
            amount: i64,
        }

        impl Configurable for MustBePositive {
            fn config_fields() -> Vec<ConfigNode> {
                vec![ConfigNode::Field(Field::new(
                    "amount",
                    "amount",
                    FieldKind::Int {
                        min: None,
                        max: None,
                        step: 1,
                        unit: None,
                    },
                ))]
            }

            fn validate(&self) -> Result<(), Vec<FieldError>> {
                if self.amount < 0 {
                    return Err(vec![FieldError::new(
                        ConfigPath::root().field("amount"),
                        "must not be negative",
                    )]);
                }
                Ok(())
            }
        }

        let settings = MustBePositive { amount: 5 };
        let patch =
            ConfigPatch::new().with(ConfigPath::root().field("amount"), ConfigValue::Int(-1));

        let errors = settings.with_patch(&patch).unwrap_err();
        assert_eq!(errors[0].message, "must not be negative");
    }
}
